export function getTeamDisplayName(originalName: string): string {
  const key = originalName.trim().toLowerCase();

  return TEAM_TRANSLATIONS[key] ?? originalName;
}

export function teamMatchesSearch(
  originalName: string,
  searchText: string
): boolean {
  const search = searchText.trim().toLowerCase();

  if (!search) {
    return true;
  }

  const original = originalName.toLowerCase();
  const translated = getTeamDisplayName(originalName).toLowerCase();

  return original.includes(search) || translated.includes(search);
}
