function normalizeTeamName(team: string): string {
  return team
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

export function isNationalTeam(team: string): boolean {
  return NATIONAL_TEAMS.has(normalizeTeamName(team));
}